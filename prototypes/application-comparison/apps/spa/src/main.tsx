import React from "react";
import { createRoot } from "react-dom/client";
import { createRootRoute, createRoute, createRouter, Outlet, RouterProvider } from "@tanstack/react-router";
import { PrototypeApplication } from "@creuza-prototype/ui";
import "@mantine/core/styles.css";
import "@creuza-prototype/ui/styles.css";
const rootRoute = createRootRoute({ component: Outlet });
const indexRoute = createRoute({ getParentRoute: () => rootRoute, path: "/", validateSearch: (search) => search, component: () => <PrototypeApplication variant="Vite + TanStack Router" /> });
const tripRoute = createRoute({ getParentRoute: () => rootRoute, path: "/trip/$tripId", validateSearch: (search) => search, component: () => <PrototypeApplication variant="Vite + TanStack Router" /> });
const router = createRouter({ routeTree: rootRoute.addChildren([indexRoute, tripRoute]), scrollRestoration: true });
createRoot(document.getElementById("root")!).render(<React.StrictMode><RouterProvider router={router} /></React.StrictMode>);
